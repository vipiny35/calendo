#[tauri::command]
fn check_for_updates() -> Result<String, String> {
    let output = std::process::Command::new("/usr/bin/curl")
        .args([
            "-fsSL",
            "--retry", "2",
            "--connect-timeout", "10",
            "https://api.github.com/repos/vipiny35/calendo/releases/latest",
            "-H", "Accept: application/vnd.github+json",
            "-H", "User-Agent: Calendo",
        ])
        .output()
        .map_err(|error| error.to_string())?;
    if !output.status.success() {
        let detail = String::from_utf8_lossy(&output.stderr).trim().to_owned();
        return Err(if detail.is_empty() {
            format!("Update server request failed ({})", output.status)
        } else {
            detail
        });
    }
    let json: serde_json::Value = serde_json::from_slice(&output.stdout)
        .map_err(|error| error.to_string())?;
    json.get("tag_name")
        .and_then(serde_json::Value::as_str)
        .map(str::to_owned)
        .ok_or_else(|| "No release found".into())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_autostart::init(
            MacosLauncher::LaunchAgent,
            Some(vec![AUTOSTART_ARG]),
        ))
        .setup(|app| {
            let _ = app.set_activation_policy(ActivationPolicy::Accessory);
            let user_data = user_data_dir(app.handle());
            std::fs::create_dir_all(&user_data).ok();
            let store = SettingsStore::load(user_data);
            let initial = store.value();
            app.manage(AppState {
                settings: Mutex::new(store),
                ignore_calendar_blur: AtomicBool::new(false),
                calendar_pinned: AtomicBool::new(false),
                events_screen_height: Mutex::new(EVENTS_FALLBACK_SCREEN),
            });
            set_launch_at_login(app.handle(), initial.launch_at_login);
            build_calendar_window(app.handle())?;
            build_events_window(app.handle())?;
            build_settings_window(app.handle())?;
            apply_app_theme(app.handle(), &initial.theme);
            build_tray(app.handle())?;
            spawn_clock(app.handle().clone());
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            get_settings,
            update_settings,
            set_tray_label,
            set_event_tray_label,
            beep,
            hide_calendar,
            hide_events,
            set_events_height,
            popover_material,
            set_calendar_pinned,
            open_settings,
            quit_app,
            app_version,
            check_for_updates,
            get_upcoming_event,
            get_calendar_events,
            request_calendar_access,
            get_calendar_access,
            join_meeting,
            open_event,
        ])
        .run(tauri::generate_context!())
        .expect("Calendo failed to start");
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A window missing from the capability cannot listen for events, and
    /// nothing fails loudly: its own commands keep working while every
    /// `listen` is refused, so the popover simply stops refreshing.
    #[test]
    fn every_window_is_granted_the_core_capability() {
        let capability: serde_json::Value =
            serde_json::from_str(include_str!("../capabilities/default.json"))
                .expect("capability is valid JSON");
        let windows = capability["windows"]
            .as_array()
            .expect("capability names its windows");
        for label in [CALENDAR_LABEL, EVENTS_LABEL, SETTINGS_LABEL] {
            assert!(
                windows.iter().any(|window| window == label),
                "window {label} is missing from capabilities/default.json"
            );
        }
    }

    #[test]
    fn events_popover_takes_its_content_height_under_a_ceiling() {
        // No minimum of its own: a short list gets a short window.
        assert_eq!(events_height(120.0, 982.0), 120.0);
        assert_eq!(events_height(300.0, 982.0), 300.0);
        // The ceiling keeps the whole popover on the display.
        assert_eq!(events_height(3000.0, 982.0), 982.0 * EVENTS_SCREEN_SHARE);
        assert_eq!(events_height(700.0, 600.0), 600.0 * EVENTS_SCREEN_SHARE);
        assert_eq!(events_height(f64::NAN, 982.0), EVENTS_FLOOR);
        assert_eq!(events_height(0.0, 982.0), EVENTS_FLOOR);
        // A screen too short for the floor still yields a usable window.
        assert_eq!(events_height(400.0, 20.0), EVENTS_FLOOR);
    }

    // Retina laptop below a 1× external, matching a typical arrangement:
    // laptop (0, 0) 1512×982 @2x, external (−197, −1080) 1920×1080 @1x.
    const LAPTOP: ScreenBounds = ScreenBounds {
        x: 0.0,
        y: 0.0,
        width: 3024.0,
        height: 1964.0,
    };
    const EXTERNAL: ScreenBounds = ScreenBounds {
        x: -197.0,
        y: -1080.0,
        width: 1920.0,
        height: 1080.0,
    };

    #[test]
    fn picks_the_display_the_tray_is_on() {
        let screens = [LAPTOP, EXTERNAL];
        assert_eq!(screen_containing(&screens, 1512.0, 100.0), Some(LAPTOP));
        assert_eq!(screen_containing(&screens, 500.0, -1070.0), Some(EXTERNAL));
    }

    #[test]
    fn sits_under_the_tray_on_a_1x_display_above_the_laptop() {
        let (x, y, placement) =
            popover_origin(500.0, -1080.0, 40.0, 24.0, 340.0, 326.0, EXTERNAL);
        assert_eq!(x, 350.0);
        assert_eq!(y, -1056.0);
        assert_eq!(placement, PopoverPlacement::Below);
        assert!(point_in_screen(x, y, EXTERNAL));
        assert!(!point_in_screen(x, y, LAPTOP));
    }

    #[test]
    fn sits_under_the_tray_on_the_built_in_display() {
        let (x, y, placement) = popover_origin(
            1200.0,
            0.0,
            40.0,
            24.0,
            340.0,
            326.0,
            ScreenBounds {
                x: 0.0,
                y: 0.0,
                width: 1512.0,
                height: 982.0,
            },
        );
        assert_eq!(x, 1050.0);
        assert_eq!(y, 24.0);
        assert_eq!(placement, PopoverPlacement::Below);
    }

    #[test]
    fn stays_on_the_tray_screen_when_the_icon_is_near_the_edge() {
        let (x, y, placement) =
            popover_origin(-180.0, -1080.0, 40.0, 24.0, 340.0, 326.0, EXTERNAL);
        assert_eq!(x, EXTERNAL.x + 8.0);
        assert_eq!(y, -1056.0);
        assert_eq!(placement, PopoverPlacement::Below);
        assert!(point_in_screen(x, y, EXTERNAL));
    }

    #[test]
    fn caret_stays_on_the_icon_when_the_window_is_centered() {
        assert_eq!(caret_offset(370.0, 300.0, 500.0, 40.0), 150.0);
    }

    #[test]
    fn caret_follows_the_icon_when_the_window_is_clamped() {
        assert_eq!(caret_offset(-189.0, 340.0, -180.0, 40.0), 29.0);
    }

    #[test]
    fn caret_stays_inside_the_card_near_a_corner() {
        assert_eq!(caret_offset(8.0, 300.0, 8.0, 24.0), 22.0);
    }
}
